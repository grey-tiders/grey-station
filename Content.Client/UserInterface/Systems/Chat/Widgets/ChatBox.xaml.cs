using Content.Shared._ES.Chat;
using Content.Shared.Chat;
using Content.Shared.Input;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;
using static Robust.Client.UserInterface.Controls.LineEdit;

namespace Content.Client.UserInterface.Systems.Chat.Widgets;

[GenerateTypedNameReferences]
[Virtual]
public partial class ChatBox : UIWidget
{
    [Dependency] protected IEntityManager EntManager = default!;
    [Dependency] protected IPrototypeManager PrototypeManager = default!;
    [Dependency] private ILogManager _log = default!;

    protected readonly ISawmill Sawmill;
    protected readonly ChatUIController Controller;

    private ESChatMessage? _lastEmote;
    private int _emoteCount;

    public bool Main { get; set; }

    public ProtoId<ESChatChannelPrototype> SelectedChannel => ChatInput.ChannelSelector.SelectedChannel;

    public ChatBox()
    {
        RobustXamlLoader.Load(this);
        Sawmill = _log.GetSawmill("chat");

        ChatInput.Input.OnTextEntered += OnTextEntered;
        ChatInput.Input.OnKeyBindDown += OnInputKeyBindDown;
        ChatInput.Input.OnTextChanged += OnTextChanged;
        ChatInput.Input.OnFocusEnter += OnFocusEnter;
        ChatInput.Input.OnFocusExit += OnFocusExit;
        ChatInput.ChannelSelector.OnChannelSelect += OnChannelSelect;
        ChatInput.FilterButton.Popup.OnChannelFilter += OnChannelFilter;
        Controller = UserInterfaceManager.GetUIController<ChatUIController>();
        Controller.MessageAdded += OnMessageAdded;
        Controller.RegisterChat(this);
        Controller.UpdateSelectedChannel(this);
    }

    private void OnTextEntered(LineEditEventArgs args)
    {
        Controller.SendMessage(this, SelectedChannel);
    }

    protected virtual void OnMessageAdded(ESChatMessage msg)
    {
        Sawmill.Debug($"{msg.Channel}: {msg.Content}");
        if (!VisibleInTree)
            return;

        if (!ChatInput.FilterButton.Popup.IsActive(msg.Channel))
        {
            return;
        }

        msg.Read = true;

        AddChatMessage(msg, PrototypeManager.Index(msg.Channel));
    }

    private void OnHighlightsUpdated(string highlights)
    {
        ChatInput.FilterButton.Popup.UpdateHighlights(highlights);
    }

    private void OnChannelSelect(ProtoId<ESChatChannelPrototype> channel)
    {
        Controller.NotifyChatSelectorChanged(this);
        Controller.NotifyChatTextChange(this);
    }

    public virtual void Repopulate()
    {
        Contents.Clear();
        _lastEmote = null;

        foreach (var message in Controller.History)
        {
            OnMessageAdded(message.Item2);
        }
    }

    protected virtual void OnChannelFilter(ProtoId<ESChatChannelFilterPrototype> channel, bool active)
    {
        Repopulate();

        if (active)
        {
            Controller.ClearUnfilteredUnreads(channel);
        }
    }

    public void AddLine(string message, Color color)
    {
        _lastEmote = null;
        RenderLine(message, color);
    }

    protected void AddChatMessage(ESChatMessage message, ESChatChannelPrototype channel)
    {
        var text = message.FormattedMessage;
        if (channel.SpeechBubbleType != SpeechType.Emote ||
            ((message.Source == null || message.Source == NetEntity.Invalid) && message.SourceKey == null))
        {
            AddLine(text, message.Color);
            return;
        }

        if (_lastEmote is { } previous &&
            previous.Source == message.Source &&
            previous.SourceKey == message.SourceKey &&
            previous.Channel == message.Channel &&
            previous.Color == message.Color &&
            previous.FormattedMessage == text)
        {
            _emoteCount++;
        }
        else
        {
            _emoteCount = 1;
        }

        _lastEmote = message;
        RenderLine(text, message.Color, _emoteCount);
    }

    private void RenderLine(string message, Color color, int count = 1)
    {
        var formatted = new FormattedMessage(3);
        formatted.PushColor(color);
        formatted.AddMarkupOrThrow(message);
        formatted.Pop();
        if (count > 1)
        {
            formatted.AddText(Loc.GetString("chat-emote-repeat-count", ("count", count)));
            Contents.SetMessage(^1, formatted, tagsAllowed: null);
        }
        else
        {
            Contents.AddMessage(formatted, tagsAllowed: null);
        }
    }

    public void Focus(ProtoId<ESChatChannelPrototype>? channel = null)
    {
        var input = ChatInput.Input;
        var selectStart = Index.End;

        if (channel != null && Controller.GetPermittedChannels().Contains(channel.Value))
            ChatInput.ChannelSelector.Select(channel.Value);

        input.IgnoreNext = true;
        input.GrabKeyboardFocus();

        input.CursorPosition = input.Text.Length;
        input.SelectionStart = selectStart.GetOffset(input.Text.Length);
    }

    public void CycleChatChannel(bool forward)
    {
        var channels = ChatInput.ChannelSelector.Popup.Channels;

        var idx = channels.IndexOf(SelectedChannel);
        idx += forward ? 1 : -1;
        idx = MathHelper.Mod(idx, channels.Count);

        ChatInput.ChannelSelector.Select(channels[idx]);
    }

    private void OnInputKeyBindDown(GUIBoundKeyEventArgs args)
    {
        if (args.Function == EngineKeyFunctions.TextReleaseFocus)
        {
            ChatInput.Input.ReleaseKeyboardFocus();
            ChatInput.Input.Clear();
            args.Handle();
            return;
        }

        if (args.Function == ContentKeyFunctions.CycleChatChannelForward)
        {
            CycleChatChannel(true);
            args.Handle();
            return;
        }

        if (args.Function == ContentKeyFunctions.CycleChatChannelBackward)
        {
            CycleChatChannel(false);
            args.Handle();
        }
    }

    private void OnTextChanged(LineEditEventArgs args)
    {
        // Update channel select button to correct channel if we have a prefix.
        Controller.UpdateSelectedChannel(this);

        // Warn typing indicator about change
        Controller.NotifyChatTextChange(this);
    }

    private void OnFocusEnter(LineEditEventArgs args)
    {
        // Warn typing indicator about focus
        Controller.NotifyChatFocus(this, true);
    }

    private void OnFocusExit(LineEditEventArgs args)
    {
        // Warn typing indicator about focus
        Controller.NotifyChatFocus(this, false);
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (!disposing) return;
        Controller.UnregisterChat(this);
        ChatInput.Input.OnTextEntered -= OnTextEntered;
        ChatInput.Input.OnKeyBindDown -= OnInputKeyBindDown;
        ChatInput.Input.OnTextChanged -= OnTextChanged;
        ChatInput.ChannelSelector.OnChannelSelect -= OnChannelSelect;
    }
}
